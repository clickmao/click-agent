"""Wythoff game: LOSE on cold positions, else WIN i j lexicographically smallest.

Cold positions are the P-positions of Wythoff's game, generated by the
complementary Beatty sequences floor(m*phi) / floor(m*phi^2).
"""


def _cold(maxv):
    s = set()
    memo = {}

    def is_cold(a, b):
        if a <= 0 or b <= 0:
            return False
        if a > b:
            a, b = b, a
        key = (a, b)
        if key not in memo:
            memo[key] = (a, b) in s
        return memo[key]

    a, b = 0, 0
    while True:
        a += 1
        b = a + a
        while (a, b) in s:
            a += 1
            b = a + a
        if a > maxv or b > maxv:
            break
        s.add((a, b))
    return s, is_cold


def solve(text: str) -> str:
    data = text.split()
    x = int(data[0])
    y = int(data[1])
    size = max(x, y) + 1
    inf = float('inf')
    moves = []
    memo = {}

    def win(a, b):
        if a == 0 and b == 0:
            return False
        if a > b:
            a, b = b, a
        key = (a, b)
        if key in memo:
            return memo[key]
        res = False
        for i in range(1, a + 1):
            if not win(a - i, b):
                res = True
                break
        if not res:
            for j in range(1, b + 1):
                if not win(a, b - j):
                    res = True
                    break
        if not res:
            for t in range(1, a + 1):
                if not win(a - t, b - t):
                    res = True
                    break
        memo[key] = res
        return res

    if not win(x, y):
        return 'LOSE'
    for i in range(0, x + 1):
        for j in range(0, y + 1):
            if i == 0 and j == 0:
                continue
            if i > 0 and j > 0 and i != j:
                continue
            if not win(x - i, y - j):
                return 'WIN ' + str(i) + ' ' + str(j)
    return 'LOSE'
